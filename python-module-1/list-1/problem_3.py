"""List-1: make_pi problem solution."""


def make_pi() -> list:
    """Return an integer array length 3 containing the first 3 digits of pi.

    Args:
        None.

    Returns:
        A list of length 3 containing [3, 1, 4].

    Complexity:
        Time Complexity: O(1)
        Space Complexity: O(1)

    Examples:
        >>> make_pi()
        [3, 1, 4]
    """
    return [3, 1, 4]


if __name__ == "__main__":
    print(make_pi())
